EXECUTE BLOCK AS
    DECLARE VARIABLE V_IDUSUARIO INTEGER;
    DECLARE VARIABLE V_MENU INTEGER;
BEGIN
    V_IDUSUARIO = NULL;

    SELECT FIRST 1 IDUSUARIO
      FROM USUARIOS
     WHERE UPPER(TRIM(LOGIN)) = 'MI'
      INTO :V_IDUSUARIO;

    IF (V_IDUSUARIO IS NOT NULL) THEN
    BEGIN
        V_MENU = 9000;

        WHILE (V_MENU <= 9017) DO
        BEGIN
            UPDATE OR INSERT INTO SIS_OPERACAOUSUARIO
                (IDUSUARIO, IDMENUITEM, IDOPERACAO, APPID, DTALTER, SIST_ALT)
            VALUES
                (:V_IDUSUARIO, :V_MENU, 900, 1, CURRENT_TIMESTAMP, 'LOCAL')
            MATCHING
                (IDUSUARIO, IDMENUITEM, IDOPERACAO, APPID);

            V_MENU = V_MENU + 1;
        END
    END
END^

