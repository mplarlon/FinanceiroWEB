FROM SIS_MAINMENU
WHERE APPID = 1
  AND IDMENUITEM BETWEEN 9000 AND 9017
ORDER BY IDMENUITEM;

/* RESULTADO 2: deve retornar o usuario MI. */
SELECT IDUSUARIO, LOGIN, NOMECOMPLETO
FROM USUARIOS
WHERE UPPER(TRIM(LOGIN)) = 'MI';

/* RESULTADO 3: deve retornar 18 permissoes. */
SELECT U.LOGIN, P.IDUSUARIO, P.IDMENUITEM, P.IDOPERACAO, P.APPID
FROM SIS_OPERACAOUSUARIO P
JOIN USUARIOS U ON U.IDUSUARIO = P.IDUSUARIO
WHERE UPPER(TRIM(U.LOGIN)) = 'MI'
  AND P.IDOPERACAO = 900
  AND P.APPID = 1
  AND P.IDMENUITEM BETWEEN 9000 AND 9017
ORDER BY P.IDMENUITEM;
