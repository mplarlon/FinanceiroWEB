EXECUTE BLOCK AS
  DECLARE VARIABLE V_MOV INTEGER;
  DECLARE VARIABLE V_DESC VARCHAR(255);
  DECLARE VARIABLE V_DATA TIMESTAMP;
BEGIN
  IF ((SELECT COUNT(*) FROM EXTRATO_ITEM WHERE CONTROLE=46745 AND MOV_BANCARIO IS NULL)=1
      AND (SELECT COUNT(*) FROM CTARECEBER WHERE CONTROLE=756648 AND IDEMPRESA=1 AND MOV_BANCARIA IS NULL)=1) THEN
  BEGIN
    SELECT DESCRICAO,DTLANCAMENTO FROM EXTRATO_ITEM WHERE CONTROLE=46745 INTO :V_DESC,:V_DATA;
    INSERT INTO MOV_BANCARIO (CDBANCO,AGENCIA,NUMCONTA,IDUSUARIO,IDEMPRESA,DESCRICAO,HISTORICO,DTLANCAMENTO,VALOR,TPLANCAMENTO,CDRECEBTO,STATUS,EXTRATO_ITEM,CONTROLE_CTA,SIST_ALT)
    VALUES (748,'4501','390143',1,1,'Conciliacao OFX',:V_DESC,:V_DATA,35.70,0,29,0,46745,756648,'LOCAL') RETURNING CONTROLE INTO :V_MOV;
    UPDATE CTARECEBER SET MOV_BANCARIA=:V_MOV WHERE CONTROLE=756648 AND IDEMPRESA=1;
    UPDATE EXTRATO_ITEM SET MOV_BANCARIO=:V_MOV WHERE CONTROLE=46745;
  END
END^

