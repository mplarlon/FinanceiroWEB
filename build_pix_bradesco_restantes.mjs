import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const raw=await fs.readFile('D:/Projetos/Dashboard/bradesco_pix_restantes.tsv','utf8');
const rows=raw.split(/\r?\n/).filter(x=>x.trim()).map(line=>{
  const p=line.split('\t').map(x=>x.trim());
  return [+p[0],new Date(`${p[1]}T12:00:00`),+p[2],p[3]||'',p.slice(4).join(' ').trim()];
});
const total=Math.round(rows.reduce((a,x)=>a+x[2],0)*100)/100;
const outDir='D:/Projetos/Dashboard/outputs/reconciliacao_setembro_2026';
const outPath=`${outDir}/PIX_Bradesco_nao_conciliados_ate_28-09-2026.xlsx`;
const wb=Workbook.create();
const sh=wb.worksheets.add('PIX pendentes');
sh.showGridLines=false;
sh.tabColor='#9E1B32';
sh.getRange('A2:E2').values=[['PIX do Bradesco ainda não conciliados — até 28/09/2026','','','','']];
sh.getRange('A4:B5').values=[['Quantidade',rows.length],['Valor total',total]];
sh.getRange('A7:E7').values=[['Controle','Data','Valor (R$)','Documento','Descrição no extrato']];
sh.getRangeByIndexes(7,0,rows.length,5).values=rows;
sh.tables.add(`A7:E${rows.length+7}`,true,'PixBradescoPendentes').style='TableStyleMedium2';
sh.getRange('A2:E2').format.font={name:'Arial',size:15,bold:true,color:'#1F1F1F'};
sh.getRange('A3:E3').format.borders={bottom:{style:'thin',color:'#1F4E78'}};
sh.getRange('A4:A5').format.font={name:'Arial',size:10,bold:true,color:'#1F1F1F'};
sh.getRange('B4:B5').format.font={name:'Arial',size:10,bold:true,color:'#9E1B32'};
sh.getRange('B4').format.numberFormat='#,##0';
sh.getRange('B5').format.numberFormat='R$ #,##0.00';
sh.getRange('A7:E7').format.fill='#1F4E78';
sh.getRange('A7:E7').format.font={name:'Arial',size:10,bold:true,color:'#FFFFFF'};
sh.getRange('A7:E7').format.horizontalAlignment='center';
sh.getRange(`A8:E${rows.length+7}`).format.font={name:'Arial',size:9,color:'#1F1F1F'};
sh.getRange(`B8:B${rows.length+7}`).format.numberFormat='dd/mm/yyyy';
sh.getRange(`C8:C${rows.length+7}`).format.numberFormat='R$ #,##0.00';
sh.getRange('A:A').format.columnWidth=12;
sh.getRange('B:B').format.columnWidth=13;
sh.getRange('C:C').format.columnWidth=16;
sh.getRange('D:D').format.columnWidth=18;
sh.getRange('E:E').format.columnWidth=70;
sh.freezePanes.freezeRows(7);
wb.recalculate();
await fs.mkdir(outDir,{recursive:true});
const preview=await wb.render({sheetName:'PIX pendentes',range:'A1:E18',scale:1.2,format:'png'});
await fs.writeFile(`${outDir}/preview_pix_bradesco_restantes.png`,new Uint8Array(await preview.arrayBuffer()));
console.log((await wb.inspect({kind:'table',range:'PIX pendentes!A2:E12',include:'values,formulas',tableMaxRows:12,tableMaxCols:6})).ndjson);
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!|#SPILL!|#CALC!',options:{useRegex:true,maxResults:100},summary:'formula errors'})).ndjson);
const x=await SpreadsheetFile.exportXlsx(wb); await x.save(outPath);
console.log(JSON.stringify({outPath,count:rows.length,total}));
