SET HEADING OFF;
SET LIST OFF;
SET COUNT OFF;
SELECT CAST(I.CONTROLE AS VARCHAR(20)) || ASCII_CHAR(9) ||
       SUBSTRING(CAST(I.DTLANCAMENTO AS VARCHAR(24)) FROM 1 FOR 10) || ASCII_CHAR(9) ||
       CAST(I.VALOR AS VARCHAR(30)) || ASCII_CHAR(9) ||
       COALESCE(TRIM(I.NUMDOC),'') || ASCII_CHAR(9) ||
       REPLACE(COALESCE(TRIM(I.DESCRICAO),''),ASCII_CHAR(9),' ')
FROM EXTRATO_ITEM I
WHERE I.EXTRATO=539 AND I.MOV_BANCARIO IS NULL
  AND I.DTLANCAMENTO BETWEEN '2026-09-01' AND '2026-09-28'
  AND I.VALOR>0 AND UPPER(I.DESCRICAO) CONTAINING 'PIX'
  AND UPPER(I.DESCRICAO) NOT CONTAINING 'CIELO'
ORDER BY I.CONTROLE;
QUIT;
