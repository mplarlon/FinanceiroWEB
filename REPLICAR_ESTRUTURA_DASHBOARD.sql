/* Estrutura consolidada do Dashboard - Firebird
   Gerado a partir do codigo-fonte em C:\Dashboard.
   Execute conectado ao banco de destino. Objetos existentes sao preservados.
   As views ao final dependem das tabelas nativas do ERP.
   Arquivo ajustado para Firebird 1.5 e para o banco configurado.
   Contem somente objetos ausentes no momento da geracao. */
SET SQL DIALECT 3;

/* Todos os objetos abaixo sao condicionais. O arquivo pode ser reexecutado. */
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$GENERATORS WHERE RDB$GENERATOR_NAME = 'GEN_DASH_BOLETO')) THEN
    EXECUTE STATEMENT 'CREATE GENERATOR GEN_DASH_BOLETO';
END^

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'DASH_BOLETO')) THEN
    EXECUTE STATEMENT 'CREATE TABLE DASH_BOLETO (
      IDBOLETO BIGINT NOT NULL PRIMARY KEY, BANCO_CODIGO CHAR(3) NOT NULL,
      CONTROLE INTEGER NOT NULL, IDEMPRESA INTEGER NOT NULL,
      ID_EXTERNO VARCHAR(100), NOSSO_NUMERO VARCHAR(30),
      LINHA_DIGITAVEL VARCHAR(60), CODIGO_BARRAS VARCHAR(60),
      URL_BOLETO VARCHAR(500), STATUS VARCHAR(30) NOT NULL,
      VALOR NUMERIC(18,2) NOT NULL, VENCIMENTO DATE NOT NULL,
      PAYLOAD BLOB SUB_TYPE TEXT, RESPOSTA BLOB SUB_TYPE TEXT,
      CRIADO_EM TIMESTAMP NOT NULL, ATUALIZADO_EM TIMESTAMP NOT NULL,
      ERRO VARCHAR(1000), QR_CODE BLOB SUB_TYPE TEXT, TXID VARCHAR(100))';
END^

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'DASH_BOLETO_EVENTO')) THEN
    EXECUTE STATEMENT 'CREATE TABLE DASH_BOLETO_EVENTO (
      IDBOLETO BIGINT NOT NULL, OCORREU_EM TIMESTAMP NOT NULL,
      TIPO VARCHAR(40) NOT NULL, CONTEUDO BLOB SUB_TYPE TEXT,
      ID_EXTERNO VARCHAR(100))';
END^

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'DASH_BOLETO_ITEM')) THEN
    EXECUTE STATEMENT 'CREATE TABLE DASH_BOLETO_ITEM (
      IDBOLETO BIGINT NOT NULL, CONTROLE INTEGER NOT NULL,
      IDEMPRESA INTEGER NOT NULL, VALOR NUMERIC(18,2) NOT NULL,
      PRIMARY KEY (IDBOLETO, CONTROLE, IDEMPRESA))';
END^
SET TERM ; ^

SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'DASH_BOLETO' AND RDB$FIELD_NAME = 'QR_CODE')) THEN
    EXECUTE STATEMENT 'ALTER TABLE DASH_BOLETO ADD QR_CODE BLOB SUB_TYPE TEXT';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'DASH_BOLETO' AND RDB$FIELD_NAME = 'TXID')) THEN
    EXECUTE STATEMENT 'ALTER TABLE DASH_BOLETO ADD TXID VARCHAR(100)';
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'DASH_BOLETO_EVENTO' AND RDB$FIELD_NAME = 'ID_EXTERNO')) THEN
    EXECUTE STATEMENT 'ALTER TABLE DASH_BOLETO_EVENTO ADD ID_EXTERNO VARCHAR(100)';
END^
SET TERM ; ^

/* Estrutura de acordos e auditoria financeira. */
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$GENERATORS WHERE RDB$GENERATOR_NAME = 'GEN_DASH_FIN_ACORDO')) THEN
    EXECUTE STATEMENT 'CREATE GENERATOR GEN_DASH_FIN_ACORDO';
  IF (NOT EXISTS(SELECT 1 FROM RDB$GENERATORS WHERE RDB$GENERATOR_NAME = 'GEN_DASH_FIN_AUDIT')) THEN
    EXECUTE STATEMENT 'CREATE GENERATOR GEN_DASH_FIN_AUDIT';
END^

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'DASH_FIN_ACORDO')) THEN
    EXECUTE STATEMENT 'CREATE TABLE DASH_FIN_ACORDO (
      IDACORDO BIGINT NOT NULL PRIMARY KEY, TIPO VARCHAR(10) NOT NULL,
      PESSOA_ID INTEGER NOT NULL, MODELO_CONTROLE INTEGER NOT NULL,
      MODELO_EMPRESA INTEGER NOT NULL, SALDO_ORIGINAL NUMERIC(18,2) NOT NULL,
      JUROS NUMERIC(18,2) DEFAULT 0, DESCONTO NUMERIC(18,2) DEFAULT 0,
      RETENCAO NUMERIC(18,2) DEFAULT 0, ACRESCIMO NUMERIC(18,2) DEFAULT 0,
      TOTAL_NOVO NUMERIC(18,2) NOT NULL, STATUS VARCHAR(12) NOT NULL,
      CRIADO_EM TIMESTAMP NOT NULL, CRIADO_POR INTEGER,
      DESFEITO_EM TIMESTAMP, DESFEITO_POR INTEGER)';
END^

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'DASH_FIN_ACORDO_ITEM')) THEN
    EXECUTE STATEMENT 'CREATE TABLE DASH_FIN_ACORDO_ITEM (
      IDACORDO BIGINT NOT NULL, PAPEL CHAR(1) NOT NULL,
      CONTROLE INTEGER NOT NULL, IDEMPRESA INTEGER NOT NULL,
      STATUS_ANTERIOR INTEGER, ACORDO_ANTERIOR BIGINT,
      PRIMARY KEY (IDACORDO, PAPEL, CONTROLE, IDEMPRESA))';
END^

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'DASH_FIN_AUDIT')) THEN
    EXECUTE STATEMENT 'CREATE TABLE DASH_FIN_AUDIT (
      IDAUDIT BIGINT NOT NULL PRIMARY KEY, OPERACAO VARCHAR(30) NOT NULL,
      TIPO VARCHAR(10) NOT NULL, CONTROLE INTEGER, IDEMPRESA INTEGER,
      DETALHE VARCHAR(1000), USUARIO_ID INTEGER, DATAHORA TIMESTAMP NOT NULL)';
END^
SET TERM ; ^

/* Atualiza instalacoes que ja tinham a tabela de itens em versao anterior. */
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(
      SELECT 1 FROM RDB$RELATION_FIELDS
      WHERE RDB$RELATION_NAME = 'DASH_FIN_ACORDO_ITEM'
        AND RDB$FIELD_NAME = 'ACORDO_ANTERIOR'
  )) THEN
    EXECUTE STATEMENT
      'ALTER TABLE DASH_FIN_ACORDO_ITEM ADD ACORDO_ANTERIOR BIGINT';
END^
SET TERM ; ^

/* Campo nativo exigido pelo Dashboard de Vendas.
   O bloco permite executar o consolidado em bancos com ou sem a coluna. */
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(
      SELECT 1 FROM RDB$RELATION_FIELDS
      WHERE RDB$RELATION_NAME = 'SAIDAPRODUTO'
        AND RDB$FIELD_NAME = 'VLCUSTOREAL'
  )) THEN
    EXECUTE STATEMENT
      'ALTER TABLE SAIDAPRODUTO ADD VLCUSTOREAL DOUBLE PRECISION';
END^
SET TERM ; ^

SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'UX_DASH_BOLETO_TITULO')) THEN
    EXECUTE STATEMENT 'CREATE UNIQUE INDEX UX_DASH_BOLETO_TITULO ON DASH_BOLETO (CONTROLE, IDEMPRESA)';
  IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'UX_DASH_BOL_EVT_EXT')) THEN
    EXECUTE STATEMENT 'CREATE UNIQUE INDEX UX_DASH_BOL_EVT_EXT ON DASH_BOLETO_EVENTO (ID_EXTERNO)';
END^
SET TERM ; ^

COMMIT;

/* Conferencia final: as quatro linhas abaixo precisam aparecer. */
SELECT 'TABELA' AS TIPO, TRIM(RDB$RELATION_NAME) AS OBJETO
FROM RDB$RELATIONS
WHERE RDB$RELATION_NAME IN ('DASH_FIN_ACORDO', 'DASH_FIN_ACORDO_ITEM', 'DASH_FIN_AUDIT')
UNION ALL
SELECT 'CAMPO', TRIM(RDB$RELATION_NAME) || '.' || TRIM(RDB$FIELD_NAME)
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME = 'SAIDAPRODUTO' AND RDB$FIELD_NAME = 'VLCUSTOREAL';


