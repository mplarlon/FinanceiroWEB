      EXECUTE STATEMENT 'ALTER TABLE DP_FUNCIONARIO ADD DATA_FIM_EXPERIENCIA_PRORROGADA DATE';
    IF (NOT EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'DP_FUNCIONARIO' AND RDB$FIELD_NAME = 'DATA_INICIO_PERIODO_AQUISITIVO')) THEN
      EXECUTE STATEMENT 'ALTER TABLE DP_FUNCIONARIO ADD DATA_INICIO_PERIODO_AQUISITIVO DATE';
    IF (NOT EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'DP_FUNCIONARIO' AND RDB$FIELD_NAME = 'DATA_FIM_PERIODO_AQUISITIVO')) THEN
      EXECUTE STATEMENT 'ALTER TABLE DP_FUNCIONARIO ADD DATA_FIM_PERIODO_AQUISITIVO DATE';
    IF (NOT EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'DP_FUNCIONARIO' AND RDB$FIELD_NAME = 'DIAS_FERIAS_DIREITO')) THEN
      EXECUTE STATEMENT 'ALTER TABLE DP_FUNCIONARIO ADD DIAS_FERIAS_DIREITO NUMERIC(10,2)';
    IF (NOT EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'DP_FUNCIONARIO' AND RDB$FIELD_NAME = 'DIAS_FERIAS_GOZADOS')) THEN
