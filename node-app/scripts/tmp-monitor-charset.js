import { loadDatabaseConfig } from "../server/config.js";
import { query, withReadOnlyDatabase } from "../server/db.js";

const legacy = (expression, size) =>
  `CAST(CAST(${expression} AS VARCHAR(${size}) CHARACTER SET OCTETS) AS VARCHAR(${size}) CHARACTER SET NONE)`;

const variants = [
  ["dup-sem-cast", `SELECT FIRST 5 t.CDCLIENTE CODIGO, COALESCE(c.CLIENTE,'Cliente') NOME, TRIM(t.NRDOC) DOCUMENTO, t.PARCELA, t.VALOR, COUNT(*) QTD
    FROM CTARECEBER t LEFT JOIN CLIENTE c ON c.CDCLIENTE=t.CDCLIENTE
    WHERE t.STATUS=1 AND t.NRDOC IS NOT NULL AND TRIM(t.NRDOC)<>''
    GROUP BY t.CDCLIENTE, c.CLIENTE, TRIM(t.NRDOC), t.PARCELA, t.VALOR HAVING COUNT(*)>1`],
  ["dup-sem-nome", `SELECT FIRST 5 t.CDCLIENTE CODIGO, TRIM(t.NRDOC) DOCUMENTO, t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2)) VALOR, COUNT(*) QTD
    FROM CTARECEBER t WHERE t.STATUS=1 AND t.NRDOC IS NOT NULL AND TRIM(t.NRDOC)<>''
    GROUP BY t.CDCLIENTE, TRIM(t.NRDOC), t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2)) HAVING COUNT(*)>1`],
  ["dup-sem-trim", `SELECT FIRST 5 t.CDCLIENTE CODIGO, COALESCE(c.CLIENTE,'Cliente') NOME, t.NRDOC DOCUMENTO, t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2)) VALOR, COUNT(*) QTD
    FROM CTARECEBER t LEFT JOIN CLIENTE c ON c.CDCLIENTE=t.CDCLIENTE
    WHERE t.STATUS=1 AND t.NRDOC IS NOT NULL
    GROUP BY t.CDCLIENTE, c.CLIENTE, t.NRDOC, t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2)) HAVING COUNT(*)>1`],
  ["dup-legacy", `SELECT FIRST 5 t.CDCLIENTE CODIGO, COALESCE(${legacy("c.CLIENTE", 80)}, CAST('Cliente' AS VARCHAR(7) CHARACTER SET NONE)) NOME,
      ${legacy("t.NRDOC", 30)} DOCUMENTO, t.PARCELA, t.VALOR VALOR, COUNT(*) QTD
    FROM CTARECEBER t LEFT JOIN CLIENTE c ON c.CDCLIENTE=t.CDCLIENTE
    WHERE t.STATUS=1 AND t.NRDOC IS NOT NULL AND CAST(t.NRDOC AS VARCHAR(30) CHARACTER SET OCTETS) <> CAST('' AS VARCHAR(1) CHARACTER SET OCTETS)
    GROUP BY t.CDCLIENTE, ${legacy("c.CLIENTE", 80)}, ${legacy("t.NRDOC", 30)}, t.PARCELA, t.VALOR HAVING COUNT(*)>1`],
  ["pagar-dup", `SELECT FIRST 5 t.CDFORNECEDOR CODIGO, COALESCE(f.FORNECEDOR,'Fornecedor') NOME, TRIM(t.NOTAFISCAL) DOCUMENTO, t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2)) VALOR, COUNT(*) QTD
    FROM CTAPAGAR t LEFT JOIN FORNECEDOR f ON f.CDFORNECEDOR=t.CDFORNECEDOR
    WHERE t.STATUS=1 AND t.NOTAFISCAL IS NOT NULL AND TRIM(t.NOTAFISCAL)<>'' AND COALESCE(t.STATUSVALE,0) NOT IN (1,2)
    GROUP BY t.CDFORNECEDOR, f.FORNECEDOR, TRIM(t.NOTAFISCAL), t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2)) HAVING COUNT(*)>1`],
];

const exact = [
  ["scan-cliente", `SELECT COUNT(*) QTD FROM CLIENTE c WHERE c.CLIENTE IS NOT NULL`],
  ["scan-trim-nrdoc", `SELECT COUNT(*) QTD FROM CTARECEBER t WHERE t.NRDOC IS NOT NULL AND TRIM(t.NRDOC)<>''`],
  ["scan-trim-nf", `SELECT COUNT(*) QTD FROM CTAPAGAR t WHERE t.NOTAFISCAL IS NOT NULL AND TRIM(t.NOTAFISCAL)<>''`],
  ["scan-produto", `SELECT COUNT(*) QTD FROM PRODUTO p WHERE p.PRODUTO IS NOT NULL`],
  ["scan-fornecedor", `SELECT COUNT(*) QTD FROM FORNECEDOR f WHERE f.FORNECEDOR IS NOT NULL`],
  ["dup-exata", `SELECT FIRST 15 t.CDCLIENTE CODIGO, COALESCE(c.CLIENTE,'Cliente') NOME,
      TRIM(t.NRDOC) DOCUMENTO, t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2)) VALOR, COUNT(*) QTD
    FROM CTARECEBER t LEFT JOIN CLIENTE c ON c.CDCLIENTE=t.CDCLIENTE
    WHERE t.STATUS=1 AND t.NRDOC IS NOT NULL AND TRIM(t.NRDOC)<>''
    GROUP BY t.CDCLIENTE, c.CLIENTE, TRIM(t.NRDOC), t.PARCELA, CAST(t.VALOR AS NUMERIC(18,2))
    HAVING COUNT(*)>1`],
  ["receber-sum", `SELECT COUNT(*) TITULOS, COALESCE(SUM(COALESCE(t.VALOR,t.DIVIDA,0)),0) TOTAL
    FROM CTARECEBER t WHERE t.STATUS=1 AND t.DTVENC<CURRENT_DATE`],
];

const tests = [
  ["receber-top", `SELECT FIRST 3 t.CDCLIENTE CODIGO, COALESCE(c.CLIENTE,'Cliente') NOME, COUNT(*) QTD
    FROM CTARECEBER t LEFT JOIN CLIENTE c ON c.CDCLIENTE=t.CDCLIENTE
    WHERE t.STATUS=1 AND t.DTVENC<CURRENT_DATE GROUP BY t.CDCLIENTE, c.CLIENTE`],
  ["receber-top-fix", `SELECT FIRST 3 t.CDCLIENTE CODIGO, COALESCE(${legacy("c.CLIENTE", 80)}, CAST('Cliente' AS VARCHAR(7) CHARACTER SET NONE)) NOME, COUNT(*) QTD
    FROM CTARECEBER t LEFT JOIN CLIENTE c ON c.CDCLIENTE=t.CDCLIENTE
    WHERE t.STATUS=1 AND t.DTVENC<CURRENT_DATE GROUP BY t.CDCLIENTE, ${legacy("c.CLIENTE", 80)}`],
  ["receber-dup", `SELECT FIRST 3 TRIM(t.NRDOC) DOCUMENTO FROM CTARECEBER t
    WHERE t.STATUS=1 AND t.NRDOC IS NOT NULL AND TRIM(t.NRDOC)<>''`],
  ["receber-dup-fix", `SELECT FIRST 3 ${legacy("t.NRDOC", 30)} DOCUMENTO FROM CTARECEBER t
    WHERE t.STATUS=1 AND t.NRDOC IS NOT NULL
      AND CAST(t.NRDOC AS VARCHAR(30) CHARACTER SET OCTETS) <> CAST('' AS VARCHAR(1) CHARACTER SET OCTETS)`],
  ["pagar-top", `SELECT FIRST 3 COALESCE(f.FORNECEDOR,'Fornecedor') NOME
    FROM CTAPAGAR t LEFT JOIN FORNECEDOR f ON f.CDFORNECEDOR=t.CDFORNECEDOR WHERE t.STATUS=1`],
  ["estoque-nome", `SELECT FIRST 3 COALESCE(p.PRODUTO,m.CDPRODUTO) NOME
    FROM MOVIMENTO m JOIN PRODUTO p ON p.CDPRODUTO=m.CDPRODUTO`],
  ["vendas-nome", `SELECT FIRST 3 COALESCE(c.CLIENTE,c.RAZAO,'Cliente') NOME
    FROM SAIDAESTOQUE se LEFT JOIN CLIENTE c ON c.CDCLIENTE=se.CDCLIENTE WHERE se.CDCLIENTE>0`],
  ["preco-unidade", `SELECT FIRST 3 pp.CDUNIDADE
    FROM PRODUTO p JOIN PRODUTOPRECO pp ON pp.CDPRODUTO=p.CDPRODUTO
      AND pp.CDUNIDADE=COALESCE(NULLIF(TRIM(p.CDUNIDVENDA),''), NULLIF(TRIM(p.CDUNIDADE),''), 'UN')
    WHERE COALESCE(p.INATIVO,0)=0`],
];

const metaSql = `SELECT TRIM(rf.RDB$RELATION_NAME) RELACAO, TRIM(rf.RDB$FIELD_NAME) CAMPO,
  f.RDB$CHARACTER_LENGTH TAMANHO, f.RDB$CHARACTER_SET_ID CHARSET
  FROM RDB$RELATION_FIELDS rf JOIN RDB$FIELDS f ON f.RDB$FIELD_NAME = rf.RDB$FIELD_SOURCE
  WHERE TRIM(rf.RDB$RELATION_NAME) IN ('CLIENTE','FORNECEDOR','PRODUTO','VENDEDOR','CTARECEBER','CTAPAGAR','SAIDAPRODUTO','ENTRPRODUTO')
    AND TRIM(rf.RDB$FIELD_NAME) IN ('CLIENTE','RAZAO','FORNECEDOR','FANTASIA','PRODUTO','VENDEDOR','NRDOC','NOTAFISCAL','DESCRICAO','CDUNIDADE','CDUNIDVENDA')`;

const files = process.argv.slice(2).filter((item) => item !== "--meta");
const base = loadDatabaseConfig();
for (const database of files) {
  console.log("\n==", database);
  try {
    await withReadOnlyDatabase(async (db) => {
      if (process.argv.includes("--meta")) {
        const rows = await query(db, metaSql, [], { timeoutMs: 20000 });
        for (const row of rows) console.log(row.RELACAO, row.CAMPO, row.TAMANHO, row.CHARSET);
        return;
      }
      for (const [name, sql] of [...variants, ...exact, ...tests]) {
        try {
          const rows = await query(db, sql, [], { timeoutMs: 25000 });
          console.log(name, "OK", rows.length, JSON.stringify(rows[0] || {}).slice(0, 180));
        } catch (error) {
          console.log(name, "FAIL", String(error.message || error).split("\n")[0]);
        }
      }
    }, { ...base, database });
  } catch (error) {
    console.log("OPEN FAIL", String(error.message || error).split("\n")[0]);
  }
}
