export async function ensureCharlieLeadsSchema(tx) {
  const tabelas = new Set((await tx.query(`SELECT TRIM(RDB$RELATION_NAME) AS NOME FROM RDB$RELATIONS WHERE COALESCE(RDB$SYSTEM_FLAG, 0) = 0`)).map((row) => row.NOME));
  const mudancas = [];
  for (const [nome, sql] of Object.entries(TABELAS)) {
    if (tabelas.has(nome)) continue;
    await tx.execute(sql);
    mudancas.push(nome);
  }
  return mudancas;
}

export async function espelharLeads(tx, estado) {
  await ensureCharlieLeadsSchema(tx);
  let gravados = 0;
  for (const lead of estado.leads || []) {
    if (!/^\d{14}$/.test(lead.cnpj || "")) continue;
    await tx.execute(`UPDATE OR INSERT INTO DASH_LEAD (
      ID, CNPJ, RAZAO, FANTASIA, UF, MUNICIPIO, CNAE, STATUS, SCORE, CLASSIFICACAO, CLIENTE_ID, VENDEDOR_ID, ORIGEM, OBTIDO_EM, ATUALIZADO_EM
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) MATCHING (CNPJ)`, [
      String(lead.id).slice(0, 36),
      lead.cnpj,
      lead.razaoSocial || null,
      lead.nomeFantasia || null,
      lead.uf || null,
      lead.municipio || null,
      lead.cnae || null,
      lead.status || "NOVO",
      Number(lead.score) || 0,
      lead.classificacao || null,
      lead.clienteId || null,
      lead.vendedorId || null,
      lead.origem || null,
      lead.obtidoEm ? new Date(lead.obtidoEm) : new Date(),
      lead.atualizadoEm ? new Date(lead.atualizadoEm) : new Date(),
    ]);
    gravados += 1;
  }
  return gravados;
}
