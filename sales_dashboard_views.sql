-- Views opcionais para acelerar e padronizar o dashboard profissional de vendas.
-- Aplicar no Firebird quando desejar materializar a camada analitica no banco.

CREATE OR ALTER VIEW VW_DASH_VENDAS_ITENS AS
SELECT
    se.IDEMPRESA,
    se.NRPEDIDO,
    CAST(se.DTSAIDA AS DATE) AS DATA_VENDA,
    se.CDVENDEDOR,
    sp.CDPRODUTO,
    p.CDGRUPO,
    p.MARCA,
    p.CDFORNECEDOR,
    COALESCE(sp.QTDPRODUTO, 0) AS QUANTIDADE,
    COALESCE(sp.TOTAL, sp.QTDPRODUTO * sp.VLUNIT, 0) AS FATURAMENTO,
    COALESCE(sp.QTDPRODUTO, 0) * COALESCE(sp.VLCUSTO, p.VLCUSTOMEDIO, 0) AS CUSTO,
    COALESCE(sp.TOTAL, sp.QTDPRODUTO * sp.VLUNIT, 0) -
        (COALESCE(sp.QTDPRODUTO, 0) * COALESCE(sp.VLCUSTO, p.VLCUSTOMEDIO, 0)) AS LUCRO_BRUTO
FROM SAIDAPRODUTO sp
JOIN SAIDAESTOQUE se
  ON se.NRPEDIDO = sp.NRPEDIDO
 AND se.IDEMPRESA = sp.IDEMPRESA
LEFT JOIN PRODUTO p
  ON p.CDPRODUTO = sp.CDPRODUTO
WHERE se.DTCANCELAMENTO IS NULL;

CREATE OR ALTER VIEW VW_DASH_VENDAS_DIA AS
SELECT
    DATA_VENDA,
    IDEMPRESA,
    CDVENDEDOR,
    COUNT(DISTINCT CAST(NRPEDIDO AS VARCHAR(20)) || '-' || CAST(IDEMPRESA AS VARCHAR(20))) AS QTD_VENDAS,
    SUM(FATURAMENTO) AS FATURAMENTO,
    SUM(CUSTO) AS CUSTO,
    SUM(LUCRO_BRUTO) AS LUCRO_BRUTO
FROM VW_DASH_VENDAS_ITENS
GROUP BY DATA_VENDA, IDEMPRESA, CDVENDEDOR;

CREATE OR ALTER VIEW VW_DASH_VENDAS_PRODUTO AS
SELECT
    CDPRODUTO,
    CDGRUPO,
    MARCA,
    CDFORNECEDOR,
    SUM(QUANTIDADE) AS QUANTIDADE,
    SUM(FATURAMENTO) AS FATURAMENTO,
    SUM(CUSTO) AS CUSTO,
    SUM(LUCRO_BRUTO) AS LUCRO_BRUTO,
    MAX(DATA_VENDA) AS ULTIMA_VENDA
FROM VW_DASH_VENDAS_ITENS
GROUP BY CDPRODUTO, CDGRUPO, MARCA, CDFORNECEDOR;

