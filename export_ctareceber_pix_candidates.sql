SET HEADING OFF;
SET LIST OFF;
SET COUNT OFF;
SELECT CAST(R.CONTROLE AS VARCHAR(20)) || ASCII_CHAR(9) ||
       SUBSTRING(CAST(R.DTMOV AS VARCHAR(24)) FROM 1 FOR 10) || ASCII_CHAR(9) ||
       CAST(COALESCE(NULLIF(R.VLPGLIQ,0),NULLIF(R.TOTALPG,0),R.VALOR) AS VARCHAR(30)) || ASCII_CHAR(9) ||
       CAST(R.STATUS AS VARCHAR(10)) || ASCII_CHAR(9) ||
       CAST(COALESCE(R.CODPAGTO,0) AS VARCHAR(10)) || ASCII_CHAR(9) ||
       CAST(COALESCE(R.TPPAGTO,0) AS VARCHAR(10))
FROM CTARECEBER R
WHERE R.MOV_BANCARIA IS NULL AND R.STATUS=2
  AND R.DTMOV BETWEEN '2026-09-01' AND '2026-10-28'
ORDER BY R.CONTROLE;
QUIT;
