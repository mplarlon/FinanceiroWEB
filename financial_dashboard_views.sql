CREATE OR ALTER VIEW VW_DASH_FIN_TITULOS AS
SELECT
    'R' AS TIPO,
    cr.CONTROLE,
    cr.IDEMPRESA,
    cr.CDCLIENTE AS ID_PESSOA,
    CAST(NULL AS INTEGER) AS CDFORNECEDOR,
    cr.CDBANCO,
    cr.CAIXA AS CDCAIXA,
    cr.CODPAGTO AS CDRECEBTO,
    cr.CDCONTA,
    cr.CDVEND AS CDVENDEDOR,
    CAST(cr.DTVENC AS DATE) AS DATA_VENCIMENTO,
    CAST(cr.DTCOB AS DATE) AS DATA_BAIXA,
    cr.STATUS,
    COALESCE(cr.DIVIDA, cr.VALOR, 0) AS VALOR_ABERTO,
    COALESCE(cr.VLPGLIQ, cr.TOTALPG, cr.VALOR, 0) AS VALOR_REALIZADO
FROM CTARECEBER cr
UNION ALL
SELECT
    'P' AS TIPO,
    cp.CONTROLE,
    cp.IDEMPRESA,
    cp.CDCLIENTEVALE AS ID_PESSOA,
    cp.CDFORNECEDOR,
    cp.CDBANCO,
    cp.CDCAIXA,
    cp.CODPAGTO AS CDRECEBTO,
    cp.CDCONTA,
    cp.CDVENDEDORVALE AS CDVENDEDOR,
    CAST(cp.DTVENC AS DATE) AS DATA_VENCIMENTO,
    CAST(cp.DTPAGTO AS DATE) AS DATA_BAIXA,
    cp.STATUS,
    COALESCE(cp.VALOR, cp.TOTAL, 0) AS VALOR_ABERTO,
    COALESCE(cp.VLPAGTO, cp.VALOR, cp.TOTAL, 0) AS VALOR_REALIZADO
FROM CTAPAGAR cp;

CREATE OR ALTER VIEW VW_DASH_FIN_MOVIMENTO AS
SELECT
    mb.CONTROLE,
    mb.IDEMPRESA,
    mb.CDBANCO,
    mb.NUMCONTA,
    mb.CDRECEBTO,
    mb.CDCONTA,
    CAST(mb.DTLANCAMENTO AS DATE) AS DATA_MOVIMENTO,
    mb.VALOR,
    CASE WHEN mb.VALOR >= 0 THEN mb.VALOR ELSE 0 END AS ENTRADA,
    CASE WHEN mb.VALOR < 0 THEN ABS(mb.VALOR) ELSE 0 END AS SAIDA,
    mb.CONTROLE_CTA
FROM MOV_BANCARIO mb;

CREATE OR ALTER VIEW VW_DASH_FIN_VENDAS AS
SELECT
    se.IDEMPRESA,
    se.NRPEDIDO,
    se.CDCLIENTE,
    se.CDVENDEDOR,
    se.CDRECEBTO,
    CAST(se.DTSAIDA AS DATE) AS DATA_VENDA,
    COALESCE(sp.TOTAL, sp.QTDPRODUTO * sp.VLUNIT, 0) AS RECEITA_BRUTA,
    COALESCE(sp.DESCONTO, 0) + COALESCE(se.DESCONTO, 0) AS DESCONTOS,
    COALESCE(sp.QTDPRODUTO, 0) * COALESCE(sp.VLCUSTO, p.VLCUSTOMEDIO, 0) AS CUSTO,
    COALESCE(sp.TOTAL, sp.QTDPRODUTO * sp.VLUNIT, 0) -
        (COALESCE(sp.QTDPRODUTO, 0) * COALESCE(sp.VLCUSTO, p.VLCUSTOMEDIO, 0)) AS LUCRO_BRUTO
FROM SAIDAPRODUTO sp
JOIN SAIDAESTOQUE se
  ON se.NRPEDIDO = sp.NRPEDIDO
 AND se.IDEMPRESA = sp.IDEMPRESA
LEFT JOIN PRODUTO p
  ON p.CDPRODUTO = sp.CDPRODUTO
WHERE se.DTCANCELAMENTO IS NULL;

CREATE OR ALTER VIEW VW_DASH_FIN_DRE AS
SELECT
    DATA_VENDA AS DATA_REFERENCIA,
    IDEMPRESA,
    'RECEITA_BRUTA' AS LINHA,
    SUM(RECEITA_BRUTA) AS VALOR
FROM VW_DASH_FIN_VENDAS
GROUP BY DATA_VENDA, IDEMPRESA
UNION ALL
SELECT
    DATA_VENDA,
    IDEMPRESA,
    'DEDUCOES',
    SUM(DESCONTOS) * -1
FROM VW_DASH_FIN_VENDAS
GROUP BY DATA_VENDA, IDEMPRESA
UNION ALL
SELECT
    DATA_VENDA,
    IDEMPRESA,
    'CMV',
    SUM(CUSTO) * -1
FROM VW_DASH_FIN_VENDAS
GROUP BY DATA_VENDA, IDEMPRESA;

