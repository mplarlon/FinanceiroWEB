SET HEADING OFF;
SET LIST OFF;
SET COUNT OFF;
SELECT
  CAST(I.CONTROLE AS VARCHAR(20)) || ASCII_CHAR(9) ||
  CAST(E.CONTROLE AS VARCHAR(20)) || ASCII_CHAR(9) ||
  TRIM(E.DESCRICAO) || ASCII_CHAR(9) ||
  SUBSTRING(CAST(I.DTLANCAMENTO AS VARCHAR(24)) FROM 1 FOR 10) || ASCII_CHAR(9) ||
  CASE WHEN I.VALOR >= 0 THEN 'ENTRADA' ELSE 'SAIDA' END || ASCII_CHAR(9) ||
  CAST(ABS(I.VALOR) AS VARCHAR(30)) || ASCII_CHAR(9) ||
  COALESCE(TRIM(I.NUMDOC),'') || ASCII_CHAR(9) ||
  REPLACE(REPLACE(COALESCE(TRIM(I.DESCRICAO),''), ASCII_CHAR(9), ' '), ASCII_CHAR(13), ' ')
FROM EXTRATO_ITEM I
JOIN EXTRATO E ON E.CONTROLE=I.EXTRATO
WHERE I.MOV_BANCARIO IS NULL
  AND I.DTLANCAMENTO BETWEEN '2026-09-01' AND '2026-09-28'
  AND I.EXTRATO IN (539,543,551)
ORDER BY E.CONTROLE,I.DTLANCAMENTO,I.CONTROLE;
QUIT;
