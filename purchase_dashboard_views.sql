-- Views opcionais para consolidar indicadores do dashboard de compras.
-- Aplicar no Firebird quando quiser acelerar consultas repetidas.

CREATE OR ALTER VIEW VW_DASH_COMPRAS_ITENS AS
SELECT
    ee.IDENTRADA,
    ee.IDEMPRESA,
    ee.CDORDEM,
    ee.CDFORNECEDOR,
    ee.NOTAFISCAL,
    CAST(ee.DTENTRADA AS DATE) AS DATA_ENTRADA,
    ee.CDVENDEDOR AS COMPRADOR,
    ep.CDPRODUTO,
    COALESCE(p.PRODUTO, ep.DESCRICAO, ep.CDPRODUTO) AS PRODUTO,
    p.CDGRUPO,
    COALESCE(g.GRUPOS, p.GRUPO) AS GRUPO,
    p.MARCA,
    COALESCE(ep.QTDE, 0) AS QUANTIDADE,
    COALESCE(ep.VLUNIT, 0) AS VALOR_UNITARIO,
    COALESCE(ep.VLCUSTO, ep.VLUNIT, 0) AS CUSTO_ATUAL,
    COALESCE(ep.CUSTOMED_ANTERIOR, 0) AS CUSTO_ANTERIOR,
    COALESCE(ep.VLTOT, ep.QTDE * ep.VLUNIT, 0) AS VALOR_TOTAL,
    COALESCE(ee.TRANSFESTOQUE, 0) AS TRANSFESTOQUE
FROM ENTRPRODUTO ep
JOIN ENTRESTOQUE ee ON ee.IDENTRADA = ep.IDENTRADA AND ee.IDEMPRESA = ep.IDEMPRESA
LEFT JOIN PRODUTO p ON p.CDPRODUTO = ep.CDPRODUTO
LEFT JOIN GRUPOS g ON g.CDGRUPO = p.CDGRUPO
WHERE ee.DTCANCELAMENTO IS NULL;

CREATE OR ALTER VIEW VW_DASH_COMPRAS_DIA AS
SELECT
    DATA_ENTRADA,
    IDEMPRESA,
    COUNT(DISTINCT IDENTRADA) AS ENTRADAS,
    COUNT(DISTINCT CDORDEM) AS PEDIDOS,
    SUM(QUANTIDADE) AS QUANTIDADE,
    SUM(VALOR_TOTAL) AS VALOR_TOTAL
FROM VW_DASH_COMPRAS_ITENS
GROUP BY DATA_ENTRADA, IDEMPRESA;

CREATE OR ALTER VIEW VW_DASH_COMPRAS_PRODUTO AS
SELECT
    CDPRODUTO,
    PRODUTO,
    CDGRUPO,
    GRUPO,
    MARCA,
    COUNT(DISTINCT IDENTRADA) AS ENTRADAS,
    COUNT(DISTINCT CDFORNECEDOR) AS FORNECEDORES,
    SUM(QUANTIDADE) AS QUANTIDADE,
    SUM(VALOR_TOTAL) AS VALOR_TOTAL,
    AVG(NULLIF(CUSTO_ANTERIOR, 0)) AS CUSTO_ANTERIOR_MEDIO,
    AVG(NULLIF(CUSTO_ATUAL, 0)) AS CUSTO_ATUAL_MEDIO
FROM VW_DASH_COMPRAS_ITENS
GROUP BY CDPRODUTO, PRODUTO, CDGRUPO, GRUPO, MARCA;

CREATE OR ALTER VIEW VW_DASH_COMPRAS_FORNECEDOR AS
SELECT
    i.CDFORNECEDOR,
    COALESCE(f.FORNECEDOR, f.FANTASIA, CAST(i.CDFORNECEDOR AS VARCHAR(20))) AS FORNECEDOR,
    COUNT(DISTINCT i.IDENTRADA) AS ENTRADAS,
    COUNT(DISTINCT i.CDORDEM) AS PEDIDOS,
    COUNT(DISTINCT i.CDPRODUTO) AS PRODUTOS,
    SUM(i.QUANTIDADE) AS QUANTIDADE,
    SUM(i.VALOR_TOTAL) AS VALOR_TOTAL
FROM VW_DASH_COMPRAS_ITENS i
LEFT JOIN FORNECEDOR f ON f.CDFORNECEDOR = i.CDFORNECEDOR
GROUP BY i.CDFORNECEDOR, f.FORNECEDOR, f.FANTASIA;
